## Настройки, о которых стоит знать

**«Блокировать трафик мимо туннеля»** (kill switch, выключен по умолчанию).
Если ядро упадёт, интернет отключится, а не пойдёт открытым. Проверено
замером: без него в момент падения ядра наружу уходит реальный адрес.
Ограничение: правила привязаны к сетевому интерфейсу, активному в момент
подключения. Пересядете с Wi-Fi на раздачу с телефона — переподключитесь.

**Сценарии.** Правило называет ПУТЬ, а не сервер: «эти сайты — мимо
туннеля», «эти — через него». Правила проверяются сверху вниз, побеждает
первое совпавшее; правило, перекрытое более ранним, клиент показывает
перечёркнутым и не даёт создать новое такое же. Правила попадают в ядро при
подключении — после правки нажмите «Применить».

