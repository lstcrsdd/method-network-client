#!/bin/bash
#
# Выпуск standalone-клиента **Method** для macOS.
#
# Скрипт НИЧЕГО НЕ ПУБЛИКУЕТ. Он собирает, проверяет, упаковывает, считает
# sha256 и печатает готовую команду `gh release create` — выполнить её должен
# владелец руками. Публикация — осознанное действие, а не побочный эффект.
#
# Использование:
#   ./Scripts/release.sh                 # полный цикл (чистая сборка)
#   METHOD_SKIP_CLEAN=1 ./Scripts/release.sh   # без `clean` (быстрее, для отладки скрипта)
#
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # .../MacOS
REPO_DIR="$(cd "$SRC_DIR/.." && pwd)"                        # корень репозитория
OUT_DIR="$REPO_DIR/Release"
SCHEME="Method"

# Сборка ОБЯЗАНА идти вне синхронизируемой папки (iCloud/Dropbox): синхронизация
# навешивает на файлы расширенные атрибуты уже ПОСЛЕ подписи, и проверка подписи
# падает с «resource fork, Finder information, or similar detritus not allowed».
# Ловится ровно на выпуске — Debug при этом собирается как ни в чём не бывало.
BUILD_DIR="${METHOD_RELEASE_BUILD_DIR:-/tmp/method-release}"

step()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
ok()    { printf '    \033[32m✓\033[0m %s\n' "$*"; }
fail()  { printf '\n\033[31mОШИБКА: %s\033[0m\n' "$*" >&2; exit 1; }

# --- 0. Куда собираем -------------------------------------------------------

case "$BUILD_DIR" in
    "$REPO_DIR"/*|"$REPO_DIR")
        fail "каталог сборки ($BUILD_DIR) внутри репозитория. Репозиторий лежит на Desktop,
       то есть в зоне синхронизации — подпись будет испорчена. Используйте /tmp." ;;
    "$HOME"/Desktop/*|"$HOME"/Documents/*|"$HOME"/Library/Mobile\ Documents/*)
        fail "каталог сборки ($BUILD_DIR) в синхронизируемой папке. Используйте /tmp." ;;
esac

step "Готовим каталог сборки: $BUILD_DIR"
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR" "$OUT_DIR"
ok "чисто"

# --- 1. Проект из project.yml ----------------------------------------------

XCODEGEN="$SRC_DIR/.tools/xcodegen/bin/xcodegen"
if [ -x "$XCODEGEN" ]; then
    step "Пересобираем MethodVPN.xcodeproj из project.yml"
    (cd "$SRC_DIR" && "$XCODEGEN" generate >/dev/null)
    ok "проект сгенерирован (версия из project.yml поедет в бандл)"
else
    printf '    ! xcodegen не найден (%s) — собираем существующий .xcodeproj\n' "$XCODEGEN"
    printf '      Если правили project.yml, версия в бандле будет СТАРОЙ.\n'
fi

# --- 2. Сборка Release ------------------------------------------------------

step "Сборка $SCHEME (Release)"
BUILD_ACTION="clean build"
[ -n "${METHOD_SKIP_CLEAN:-}" ] && BUILD_ACTION="build"
(cd "$SRC_DIR" && xcodebuild -scheme "$SCHEME" -configuration Release \
    -derivedDataPath "$BUILD_DIR" $BUILD_ACTION -quiet) \
    || fail "сборка не прошла"
ok "собрано"

APP="$BUILD_DIR/Build/Products/Release/Method.app"
[ -d "$APP" ] || fail "не нашёл $APP"

VERSION="$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$APP/Contents/Info.plist")"
BUILD_NO="$(/usr/libexec/PlistBuddy -c 'Print CFBundleVersion' "$APP/Contents/Info.plist")"
[ -n "$VERSION" ] || fail "в Info.plist пустой CFBundleShortVersionString"
[ -n "$BUILD_NO" ] || fail "в Info.plist пустой CFBundleVersion — номер сборки обязателен"
ok "версия $VERSION (сборка $BUILD_NO)"

# --- 3. Комплектность бандла ------------------------------------------------

step "Проверяем комплектность бандла"
for f in \
    "Contents/MacOS/Method" \
    "Contents/MacOS/network.method.client.helper" \
    "Contents/Library/LaunchDaemons/network.method.client.helper.plist" \
    "Contents/Resources/sing-box"
do
    [ -e "$APP/$f" ] || fail "в бандле нет $f — комплект неполный, демон не встанет"
done
[ -x "$APP/Contents/Resources/sing-box" ] || fail "sing-box не исполняемый"
ok "демон, его plist и ядро sing-box на месте"

# Архитектуры: ядро sing-box качается под одну архитектуру. Если приложение
# универсальное, а ядра под эту архитектуру нет — на такой машине приложение
# запустится и молча не сможет подключиться. Честнее не выпускать такой бандл:
# «молчаливый отказ, выданный за успех, опаснее честной ошибки».
APP_ARCHS="$(lipo -archs "$APP/Contents/MacOS/Method")"
CORE_ARCHS="$(lipo -archs "$APP/Contents/Resources/sing-box")"
for a in $APP_ARCHS; do
    case " $CORE_ARCHS " in
        *" $a "*) ;;
        *) fail "приложение собрано под $a, а sing-box — только под '$CORE_ARCHS'.
       На такой машине Method запустится, но туннель не поднимется.
       Либо соберите ядро под $a, либо ограничьте ARCHS в project.yml." ;;
    esac
done
ok "архитектуры сходятся: приложение [$APP_ARCHS], ядро [$CORE_ARCHS]"

SINGBOX_VERSION="$("$APP/Contents/Resources/sing-box" version | head -1 | awk '{print $3}')"
SINGBOX_REVISION="$("$APP/Contents/Resources/sing-box" version | awk '/^Revision:/ {print $2}')"
ok "ядро: sing-box $SINGBOX_VERSION ($SINGBOX_REVISION)"

# --- 4. Подпись -------------------------------------------------------------

step "Проверяем подпись"
codesign --verify --deep --strict --verbose=2 "$APP" 2>&1 | sed 's/^/    /' \
    || fail "codesign --verify --deep --strict не прошла"
SIGNATURE="$(codesign -dvv "$APP" 2>&1 | awk -F= '/^Signature=/ {print $2}')"
ok "подпись действительна, тип: ${SIGNATURE:-неизвестен}"
if [ "$SIGNATURE" = "adhoc" ]; then
    printf '    ! Подпись ad-hoc: нотаризации нет, у скачавшего сработает карантин.\n'
    printf '      Инструкция для пользователя — Release/README.md (снять com.apple.quarantine).\n'
fi

# --- 5. Архив ---------------------------------------------------------------

ARCHIVE_NAME="Method-$VERSION-macos-$(echo "$APP_ARCHS" | tr ' ' '-').zip"
STAGE="$BUILD_DIR/stage"
ARCHIVE="$BUILD_DIR/$ARCHIVE_NAME"

step "Упаковываем $ARCHIVE_NAME"
rm -rf "$STAGE" && mkdir -p "$STAGE"
# ditto, а не zip: сохраняет права, симлинки и расширенные атрибуты, в которых
# лежит подпись вложенных бинарей. Обычный zip(1) их теряет, и распакованное
# приложение перестаёт проходить codesign --verify.
ditto "$APP" "$STAGE/Method.app"
(cd "$STAGE" && ditto -c -k --keepParent "Method.app" "$ARCHIVE")
ok "готово, $(du -h "$ARCHIVE" | awk '{print $1}')"

step "Контрольная распаковка (переживает ли подпись архивацию)"
VERIFY="$BUILD_DIR/verify"
rm -rf "$VERIFY" && mkdir -p "$VERIFY"
(cd "$VERIFY" && ditto -x -k "$ARCHIVE" .)
codesign --verify --deep --strict "$VERIFY/Method.app" \
    || fail "после распаковки подпись не проходит проверку — архив непригоден"
ok "распакованное приложение проходит codesign --verify --deep --strict"
rm -rf "$VERIFY"

# --- 6. Контрольная сумма и выкладка в Release/ -----------------------------

step "Считаем sha256 и кладём в $OUT_DIR"
SHA_BUILD="$(shasum -a 256 "$ARCHIVE" | awk '{print $1}')"
cp "$ARCHIVE" "$OUT_DIR/$ARCHIVE_NAME"
SHA_OUT="$(shasum -a 256 "$OUT_DIR/$ARCHIVE_NAME" | awk '{print $1}')"
[ "$SHA_BUILD" = "$SHA_OUT" ] || fail "копия в Release/ отличается от собранного архива"
echo "$SHA_OUT  $ARCHIVE_NAME" > "$OUT_DIR/$ARCHIVE_NAME.sha256"
SIZE_BYTES="$(stat -f%z "$OUT_DIR/$ARCHIVE_NAME")"
ok "$ARCHIVE_NAME — $SIZE_BYTES байт"
printf '    sha256: %s\n' "$SHA_OUT"

# --- 7. Описание релиза -----------------------------------------------------

NOTES="$OUT_DIR/RELEASE-NOTES-$VERSION.md"
TAG="method-macos-v$VERSION"

cat > "$NOTES" <<NOTESEOF
Method — VPN-клиент, который сам выбирает, каким способом пройти, и объясняет
свой выбор. Серверы в приложение не вшиты: вставьте свои ссылки
(hysteria2 / vless+reality / trojan / shadowsocks) или адрес подписки.

Ядро **sing-box** уже внутри приложения — отдельно ничего скачивать не нужно.

**Требуется:** macOS 14 и новее, Apple Silicon (архитектуры бандла: $APP_ARCHS).
Права администратора — один раз, при активации системной службы.

---

## Установка

> ⚠️ **Не открывайте приложение двойным кликом до шага 2.**
> Проверено на macOS 26: с меткой карантина Gatekeeper убивает процесс, а
> единственная кнопка в окне — «Переместить в Корзину». Кнопки «Открыть всё
> равно» не предлагается: приложение подписано локально (ad-hoc), платного
> аккаунта Apple у проекта нет, значит нет и нотаризации. Пути через
> интерфейс не существует — установка идёт командой в Терминале.
> Если уже кликнули и приложение исчезло — верните Method.app из Корзины
> в «Программы» и продолжайте с шага 2.

### Шаг 1. Скачайте архив

Файл \`$ARCHIVE_NAME\` со страницы релиза. По умолчанию он попадёт
в «Загрузки».

### Шаг 2. Установите одной командой

Откройте **Терминал** (Spotlight → «Терминал») и вставьте целиком:

\`\`\`sh
cd ~/Downloads && ditto -x -k $ARCHIVE_NAME . && xattr -dr com.apple.quarantine Method.app && mv -f Method.app /Applications/
\`\`\`

Команда делает три вещи: распаковывает архив, снимает метку карантина и
переносит приложение в «Программы».

Почему без снятия карантина нельзя: пока метка на месте, macOS запускает
приложение из временной случайной папки (App Translocation), и системная
служба оттуда не активируется в принципе. Приложение обязано лежать именно
в \`/Applications\` — служба выполняет команды только от приложения, рядом
с которым установлена.

### Шаг 3. Активируйте системную службу

Откройте **Method** (теперь можно двойным кликом), затем \`⌘,\` → вкладка
**Демон** → **Активировать**. Потребуется пароль администратора — один раз.

Служба нужна, потому что клиент поднимает **системный туннель**: заворачивает
весь трафик, а не только браузер. Создать сетевой интерфейс и прописать
маршруты без прав root нельзя.

Если статус остался «ждёт подтверждения» — откройте
Настройки системы → Основные → **«Элементы входа и расширения»**
и включите переключатель у Method. macOS иногда требует подтверждения
вручную, особенно после обновления приложения.

### Шаг 4. Добавьте свои серверы

Вкладка **Серверы** → **+**:

* **Ссылка** — вставьте \`hysteria2://…\`, \`vless://…\`, \`trojan://…\`
  или \`ss://…\`. Можно несколько строк сразу.
* **Подписка** — вставьте её адрес; клиент сам заберёт список и будет
  обновлять его.

### Шаг 5. Подключитесь

Вкладка **Обзор** → большая кнопка. При первом подключении клиент около двух
минут изучает пути — в это время маршрут держит ядро, интернет работает.
Дальше выбор переходит к движку, и следующие подключения начинаются сразу:
измерения сохраняются между запусками.

