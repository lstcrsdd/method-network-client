## Известные ограничения

* **Нет нотаризации.** Установка только через Терминал (шаг 2), обхода мышью
  не существует. После каждого обновления macOS может снова спросить
  подтверждение службы в «Элементах входа».
* **Доступность оси зависит от канала.** Пять осей заявлены, но конкретная
  сеть может резать любую из них. Замерено: на одном московском канале
  Shadowsocks не проходит вовсе, при полностью исправном сервере. Это не
  поломка — ради этого оси и считаются: клиент пометит ось мёртвой и уйдёт
  на другую.
* **Только Apple Silicon.** Сборки под Intel нет.

