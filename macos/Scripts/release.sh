## Что клиент делает сам

**Выбирает способ обхода, а не только сервер.** Протоколы сгруппированы по
пяти независимым осям: QUIC поверх UDP (Hysteria2), HTTP/2 в поддельном TLS
(Reality gRPC), голый TCP в поддельном TLS (Reality Vision), настоящий TLS
(Trojan), шифрованный поток без рукопожатия (Shadowsocks-2022). Протоколы на
одной оси убивает одна и та же причина, поэтому переключение между ними при
блокировке не даёт ничего — клиент меняет ОСЬ.

**Меняет маршрут не разрывая туннель.** Смена пути — это один запрос к
локальному API ядра, а не переподключение: соединения не рвутся.

**Объясняет свои решения.** Когда путь сменился сам, клиент пишет почему —
например «ушли с Финляндии: три пробы подряд без ответа».

**Никогда не подставляет прямой выход.** Если живых маршрутов не осталось,
полоса блокируется. Открытым трафик не пойдёт ни при каких обстоятельствах.

