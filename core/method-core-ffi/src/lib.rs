//! Граница C поверх движка Method.
//!
//! Слой не принимает решений и не хранит политики — он переводит. С одной
//! стороны Swift и его дескрипторы, с другой — чистые функции ядра, которые
//! ничего не знают ни о Swift, ни о времени, ни о сети.
//!
//! # Правило владения памятью
//!
//! Всё, что библиотека выдала наружу, освобождается ТОЛЬКО парной функцией из
//! этой же библиотеки:
//!
//! | Что выдано | Чем освобождается |
//! |------------|-------------------|
//! | `mc_engine_t*` из `mc_engine_new` | `mc_engine_free` |
//! | `mc_decision_t*` из `mc_engine_reconcile` | `mc_decision_free` |
//! | `mc_buffer_t` из `mc_engine_save_state` | `mc_buffer_free` |
//!
//! Строки НАРУЖУ ВО ВЛАДЕНИЕ НЕ ВЫДАЮТСЯ НИКОГДА. Всякая `mc_str_t` из
//! библиотеки заимствована у названного объекта и живёт ровно столько же,
//! сколько он: строки решения — до `mc_decision_free`, идентификаторы —
//! пока жив движок, текст ошибки — до следующего вызова из этого потока,
//! текст кода возврата — всё время жизни библиотеки. Освобождать их нельзя;
//! нужно пережить владельца — копируй.
//!
//! Строки, которые передают ВНУТРЬ, читаются только на время вызова и
//! копируются: после возврата вызывающий волен делать со своей памятью что
//! угодно.
//!
//! # Потоки
//!
//! Движок не рассчитан на одновременный доступ (внутри демпфера живёт `Cell`).
//! Граница это проверяет: вызов, заставший движок занятым, возвращает
//! `MC_BUSY`, а не портит состояние молча. Последовательные вызовы из разных
//! потоков безопасны.
//!
//! # Паника
//!
//! Ни одна паника не пересекает границу: каждая экспортируемая функция обёрнута
//! в `catch_unwind`. Пойманная паника даёт `MC_PANIC`, а движок помечается
//! отравленным — с наполовину изменённым состоянием работать нельзя.
//! Обязательное условие: профиль сборки НЕ должен разворачивать панику в
//! `abort` (см. комментарий в корневом `Cargo.toml`).

