//! Коды возврата и текст последней ошибки.
//!
//! Правило одно на всю границу: **функция сообщает об исходе КОДОМ, а
//! результат отдаёт через выходной параметр**. Так сделано не ради
//! единообразия, а потому что иначе неизбежна ловушка «просто ноль»: у
//! счётчика действий ноль — валидный ответ (движок решил ничего не менять), у
//! дескриптора ноль — «нет маршрута», у оценки ноль — дисквалификация. Ни одно
//! из этих значений не отличить от ошибки, если её кодировать тем же числом.
//!
//! Текст ошибки хранится отдельно и живёт в переменной потока: возвращать
//! строку в коде возврата невозможно, а выделять под неё буфер на каждый
//! промах — значит заставить вызывающего освобождать память ради сообщения,
//! которое он в девяти случаях из десяти просто запишет в журнал.

use std::cell::RefCell;

/// Коды возврата. Значения — часть ABI, менять нельзя.
#[repr(i32)]
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum Status {
    /// Успех. Единственное значение, при котором выходные параметры
    /// заполнены.
    Ok = 0,
    /// Обязательный указатель равен NULL.
    NullPointer = 1,
    /// Дескриптор маршрута или полосы неизвестен движку (или это ноль,
    /// который никогда не является дескриптором).
    InvalidHandle = 2,
    /// Строка не UTF-8.
    InvalidUtf8 = 3,
    /// Значение вне допустимого перечня или бессмысленно по существу.
    InvalidArgument = 4,
    /// Такой идентификатор уже объявлен.
    Duplicate = 5,
    /// Сущность, на которую сослались по имени, не объявлена.
    NotFound = 6,
    /// Сохранённое состояние не разбирается или собрано другой версией.
    StateInvalid = 7,
    /// Движок уже занят вызовом из другого потока. См. правило о потоках в
    /// заголовке: это НЕ повод повторять в цикле, это сигнал, что доступ не
    /// сериализован.
    Busy = 8,
    /// Внутри уже случилась паника, и состояние движка больше не считается
    /// целостным. Дальше с этим движком нельзя ничего, кроме `mc_engine_free`.
    Poisoned = 9,
    /// Паника поймана на границе. Приложение живо, движок отравлен.
    Panic = 10,
    /// Что-то, чему нет объяснения в терминах вызова. Смотри текст ошибки.
    Internal = 11,
}

impl Status {
    pub fn code(self) -> i32 {
        self as i32
    }

    /// Статический текст кода. Указывает на константу внутри библиотеки —
    /// освобождать нельзя и незачем.
    pub fn text(code: i32) -> &'static str {
        match code {
            0 => "успех",
            1 => "обязательный указатель равен NULL",
            2 => "неизвестный дескриптор",
            3 => "строка не UTF-8",
            4 => "недопустимое значение аргумента",
            5 => "идентификатор уже объявлен",
            6 => "сущность не найдена",
            7 => "сохранённое состояние не разбирается",
            8 => "движок занят вызовом из другого потока",
            9 => "движок отравлен предыдущей паникой",
            10 => "паника поймана на границе",
            11 => "внутренняя ошибка",
            _ => "неизвестный код",
        }
    }
}

/// Ошибка внутри Rust-половины: код плюс человеческое пояснение.
#[derive(Debug)]
pub struct Fail {
    pub status: Status,
    pub message: String,
}

impl Fail {
    pub fn new(status: Status, message: impl Into<String>) -> Fail {
        Fail { status, message: message.into() }
    }

    pub fn invalid(message: impl Into<String>) -> Fail {
        Fail::new(Status::InvalidArgument, message)
    }

    pub fn not_found(message: impl Into<String>) -> Fail {
        Fail::new(Status::NotFound, message)
    }

    pub fn handle(message: impl Into<String>) -> Fail {
        Fail::new(Status::InvalidHandle, message)
    }
}

thread_local! {
    /// Текст последней ошибки ЭТОГО потока.
    ///
    /// Именно потока, а не движка: ошибку может вернуть и функция, которой
    /// движок вообще не передан (разбор описания, доступ к решению). Общая на
    /// процесс переменная в этом месте означала бы, что два потока затирают
    /// друг другу диагностику.
    static LAST_ERROR: RefCell<String> = const { RefCell::new(String::new()) };
}

/// Запомнить текст и вернуть код.
pub fn fail(f: Fail) -> i32 {
    let code = f.status.code();
    LAST_ERROR.with(|slot| *slot.borrow_mut() = f.message);
    code
}

/// Успех стирает прошлую ошибку: иначе вызывающий, заглянувший в текст после
/// удачного вызова, прочитает позапрошлую беду и решит, что она свежая.
pub fn ok() -> i32 {
    LAST_ERROR.with(|slot| slot.borrow_mut().clear());
    Status::Ok.code()
}

/// Прочитать текст последней ошибки, не отдавая владения.
pub fn with_last_error<R>(f: impl FnOnce(&str) -> R) -> R {
    LAST_ERROR.with(|slot| f(&slot.borrow()))
}

/// Превратить результат Rust-половины в код возврата.
pub fn finish(r: Result<(), Fail>) -> i32 {
    match r {
        Ok(()) => ok(),
        Err(e) => fail(e),
    }
}
