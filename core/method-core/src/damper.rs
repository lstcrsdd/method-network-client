    #[test]
    fn сглаживание_идёт_по_времени_а_не_по_замерам() {
        // Активный маршрут опрашивается раз в 2 с, фоновый — раз в 20 с. Если
        // инерция считалась бы по числу замеров, их оценки стали бы
        // несравнимыми ровно там, где мы их сравниваем.
        let частый = RouteId::new("a");
        let редкий = RouteId::new("b");
        let mut d = DamperState::new();

        d.smoothed(&частый, 50.0, Instant(0));
        d.smoothed(&редкий, 50.0, Instant(0));
        for step in 1..=20u64 {
            d.smoothed(&частый, 100.0, Instant(step * 2_000));
        }
        d.smoothed(&редкий, 100.0, Instant(40_000));

        let f = d.smoothed_of(&частый).unwrap();
        let s = d.smoothed_of(&редкий).unwrap();
        assert!((f - s).abs() < 6.0, "частый {f}, редкий {s} — инерция разная");
    }

    #[test]
    fn вход_и_выход_асимметричны_и_между_ними_мёртвая_зона() {
        let (curr, margin, sticky, hys) = (80.0, 5.0, 3.0, 1.5);
        let порог = curr + margin + sticky; // 88

        assert!(should_enter(порог + hys, curr, margin, sticky, hys));
        assert!(!should_enter(порог + hys - 0.1, curr, margin, sticky, hys));

        assert!(should_exit(порог - hys - 0.1, curr, margin, sticky, hys));
        assert!(!should_exit(порог - hys + 0.1, curr, margin, sticky, hys));

        // Мёртвая зона: ни входа, ни выхода. Именно она позволяет счётчику
        // выдержки досчитать до конца, пока кандидат колеблется у порога.
        for cand in [порог - 1.0, порог, порог + 1.0] {
            assert!(!should_enter(cand, curr, margin, sticky, hys), "вход при {cand}");
            assert!(!should_exit(cand, curr, margin, sticky, hys), "выход при {cand}");
        }
    }

    #[test]
    fn выдержка_считает_серию_а_не_отдельные_замеры() {
        let lane = LaneId::new("web");
        let r = RouteId::new("r");
        let mut d = DamperState::new();

        assert_eq!(d.bump_dwell(&lane), 1);
        assert_eq!(d.bump_dwell(&lane), 2);
        d.reset_dwell(&lane);
        assert_eq!(d.bump_dwell(&lane), 1, "серия прервалась, а счётчик уцелел");

        // Состоявшееся переключение тоже обнуляет серию: иначе следующий
        // кандидат унаследовал бы чужую выдержку и ушёл бы с первого замера.
        d.bump_dwell(&lane);
        d.on_switch(&lane, &r, Instant(1_000));
        assert_eq!(d.bump_dwell(&lane), 1);
    }
