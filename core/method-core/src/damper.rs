    /// Линейный конгруэнтный генератор прямо в тесте.
    ///
    /// Никакого `rand`: ядро обязано быть воспроизводимым, и тест на дребезг —
    /// первый, кто это требует. Числа взяты из Numerical Recipes (Knuth MMIX).
    struct Lcg(u64);

    impl Lcg {
        fn next(&mut self) -> u64 {
            self.0 = self
                .0
                .wrapping_mul(6_364_136_223_846_793_005)
                .wrapping_add(1_442_695_040_888_963_407);
            self.0
        }
        fn u01(&mut self) -> f32 {
            (self.next() >> 40) as f32 / (1u64 << 24) as f32
        }
        /// Приближение N(0,1) суммой двенадцати равномерных (Irwin–Hall).
        /// Точности хвостов здесь не нужно — нужен воспроизводимый шум.
        fn gauss(&mut self) -> f32 {
            (0..12).map(|_| self.u01()).sum::<f32>() - 6.0
        }
    }

    /// Какие механизмы включены в прогоне.
    #[derive(Copy, Clone)]
    struct Набор {
        сглаживание: bool,
        шумовой_порог: bool,
        выдержка: bool,
        остывание: bool,
    }

    const ПОЛНЫЙ: Набор = Набор {
        сглаживание: true,
        шумовой_порог: true,
        выдержка: true,
        остывание: true,
    };

    /// Сколько замеров копится, прежде чем маршрут вообще участвует в выборе.
    ///
    /// Это не константа демпфера, а порог доверия из раздела 5.6, живущий в
    /// контуре решений: `confidence ≥ 0.5` набирается примерно к тридцатому
    /// замеру, то есть за две с половиной минуты. Симуляция обязана его
    /// воспроизвести, иначе она измеряет не демпфер, а холодный старт: без
    /// прогрева ВСЕ ложные переключения приходились на второй-третий шаг, где
    /// сглаживать ещё нечего и σ ещё не существует.
    const ПРОГРЕВ: u64 = 30;

    /// Час наблюдения за двумя ОБЪЕКТИВНО одинаковыми маршрутами.
    ///
    /// Оба дают оценку из одного распределения; любое переключение — ложное.
    /// Шаг 5 с, 720 шагов = ровно час, как в симуляции раздела 6.1.
    fn ложных_переключений(seed: u64, н: Набор) -> u32 {
        let a = RouteId::new("lt.trojan.8443");
        let b = RouteId::new("us.trojan.2096");
        let lane = LaneId::new("web");
        let h = Hysteresis::default();

        let mut d = DamperState::new();
        let mut rng = Lcg(seed);
        let mut current = a.clone();
        let mut switches = 0u32;

        for step in 0..720u64 {
            let now = Instant(step * 5_000);
            // Одно распределение на оба: N(85, 6) в пунктах оценки.
            let raw_a = 85.0 + 6.0 * rng.gauss();
            let raw_b = 85.0 + 6.0 * rng.gauss();

            // Сглаживание кормим всегда — иначе в прогоне без него не с чем
            // считать σ, и сравнение перестало бы быть честным.
            let sm_a = d.smoothed(&a, raw_a, now);
            let sm_b = d.smoothed(&b, raw_b, now);
            let (va, vb) = if н.сглаживание { (sm_a, sm_b) } else { (raw_a, raw_b) };

            if step < ПРОГРЕВ {
                continue;
            }
            if step == ПРОГРЕВ {
                // Первичный выбор полосы. Контур решений делает ровно это:
                // при пустом `current` он выбирает лучшего и зовёт `on_switch`.
                d.on_switch(&lane, &a, now);
                continue;
            }

            let (cur, cand, cur_s, cand_s) = if current == a {
                (&a, &b, va, vb)
            } else {
                (&b, &a, vb, va)
            };

            if d.is_suppressed(cand, now) {
                d.reset_dwell(&lane);
                continue;
            }

            let margin = if н.шумовой_порог {
                d.margin(cur, &h)
            } else {
                h.margin_floor
            };
            let sticky = d
                .switched_at(&lane)
                .map_or(0.0, |t| incumbent_bonus(t, now));

            if !should_enter(cand_s, cur_s, margin, sticky, 0.0) {
                d.reset_dwell(&lane);
                continue;
            }
            if н.выдержка && d.bump_dwell(&lane) < h.dwell {
                continue;
            }
            if н.остывание {
                if let Some(t) = d.switched_at(&lane) {
                    if now.since(t) < d.cooldown_ms(&lane, &h) {
                        continue;
                    }
                }
            }

            switches += 1;
            current = cand.clone();
            d.on_switch(&lane, cand, now);
        }
        switches
    }

