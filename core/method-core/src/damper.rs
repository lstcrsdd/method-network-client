    fn штраф_оси_бьёт_по_всем_узлам_разом() {
        // Фильтрация QUIC — свойство СЕТИ, а не серверов: Hysteria2 ложится
        // на всех нодах сразу, и наказывать надо ось, иначе исправное железо
        // получит штраф за чужую вину и будет «выздоравливать» впустую.
        let mut d = DamperState::new();
        let now = Instant(0);
        d.penalize_axis(Axis::QuicUdp, 25.0, now);

        let quic_lt = d.axis_penalty_points(Axis::QuicUdp, now);
        let quic_us = d.axis_penalty_points(Axis::QuicUdp, now);
        let quic_fi = d.axis_penalty_points(Axis::QuicUdp, now);
        assert!(quic_lt > 0.0);
        assert_eq!(quic_lt, quic_us);
        assert_eq!(quic_us, quic_fi);

        // Соседние оси не задеты — иначе штраф означал бы «всё плохо» и не
        // нёс бы информации.
        for other in [Axis::RealTls, Axis::FakeTlsH2, Axis::FakeTlsTcp, Axis::RawStream] {
            assert_eq!(d.axis_penalty_points(other, now), 0.0, "задета ось {other:?}");
        }

        // Затухает, а не остаётся навсегда: сеть, резавшая QUIC, могла
        // смениться.
        let позже = d.axis_penalty_points(Axis::QuicUdp, now.plus_ms(AXIS_PENALTY_HALF_LIFE_MS));
        assert!((позже - quic_lt / 2.0).abs() < 0.5, "через полураспад {позже}");
    }

