// Каждая подписана источником. Где источник — «наше решение», так и
// написано: через год отличить измеренную константу от выдуманной иначе
// невозможно, а лечить их надо по-разному.

/// Период полураспада сглаживания итоговой оценки.
///
/// Источник: симуляция дребезга (раздел 6.1). 40 с — это α ≈ 1/8 при шаге
/// 5 с, та самая строка таблицы, где ложных переключений ноль. Сглаживание
/// именно по ВРЕМЕНИ, а не по числу выборок: активный маршрут опрашивается
/// раз в 2 с, фоновые — раз в 20 с, и при фиксированной α их оценки имели бы
/// разную инерцию, то есть были бы несравнимы ровно там, где сравниваются.
pub const SCORE_HALF_LIFE_MS: u64 = 40_000;

/// Период полураспада оценки шума оценки.
///
/// Наша константа. σ должна быть заметно спокойнее самой оценки, иначе порог
/// начнёт дрожать вместе с тем, что он призван удержать. 120 с ≈ 24 замера
/// при шаге 5 с — тот же порядок выборки, на котором σ и мерилась
/// (4.4 пункта при n=30, 3.6 при n=60, 2.85 при n=120).
pub const NOISE_HALF_LIFE_MS: u64 = 120_000;

/// Сколько остатков нужно, прежде чем σ можно верить.
///
/// Наша константа. По одному-двум остаткам «шум» — это не шум, а случайное
/// число, и порог `2σ` из него вышел бы произвольным. До этого порога
/// используется только пол `margin_floor`.
pub const NOISE_MIN_SAMPLES: u32 = 4;

/// Во сколько σ обрезается одиночный остаток при обновлении оценки шума.
///
/// Наше решение, в документе этого нет. Без обрезки σ считает шумом то, что
/// шумом не является: когда маршрут по-настоящему проседает на двадцать
/// пунктов, огромный остаток раздувает σ, вслед за ним растёт порог
/// `max(5, 2σ)` — и деградация сама себе выписывает индульгенцию. Измерено
/// тестом `деградация_ловится_несмотря_на_демпфер`: без обрезки уход с
/// провалившегося на 25 пунктов маршрута занимает 80 с, с обрезкой — 50 с,
/// при том же нуле ложных переключений в часовой симуляции.
/// Обрезка по трём σ — приём винзоризации из робастной статистики: сдвиг
/// по-прежнему виден сглаженной оценке (её мы не трогаем), но перестаёт
/// притворяться шумом.
pub const NOISE_WINSOR_K: f32 = 3.0;

/// Множитель шума в пороге: `margin = max(floor, 2σ)`.
///
/// Источник: раздел 6.1. Порог обязан стоять НАД шумом оценки, иначе он
/// измеряет погоду. Два σ — это ~95% нормального шума, то есть переключение
/// требует выигрыша, который шумом объяснить нельзя.
pub const MARGIN_SIGMA_K: f32 = 2.0;

/// Бонус действующему маршруту, пункты.
///
/// Наша константа. Смысл — не в качестве, а в цене перехода: свежепринятое
/// решение должно немного сопротивляться пересмотру, иначе система колеблется
/// вокруг границы. Спадает линейно до нуля за 10 минут: к этому времени
/// решение перестаёт быть свежим и защищать его больше нечем.
pub const INCUMBENT_BONUS_POINTS: f32 = 3.0;

/// За сколько бонус инкумбенту спадает до нуля.
pub const INCUMBENT_DECAY_MS: u64 = 600_000;

/// Штраф за один флап. Источник: RFC 2439 (route flap damping), там же 1000.
pub const FLAP_PENALTY: f32 = 1000.0;

/// Период полураспада штрафа. Источник: RFC 2439.
pub const PENALTY_HALF_LIFE_MS: u64 = 600_000;

/// Порог подавления маршрута.
///
/// Источник: RIPE-580. И это НЕ классические 2000 из RFC 2439 — отступление
/// осознанное и вот почему. При полураспаде 10 минут и флапах раз в 10 минут
/// порог 2000 набирается за ТРИ флапа: 1000, потом 1500, потом 1750… — то
/// есть исправный маршрут с редкими колебаниями оказался бы подавлен просто
/// за то, что он живой. Порог 6000 при таком темпе не достигается никогда, а
/// при флапах раз в 30 секунд требует семи штук — то есть ловит настоящую
/// осцилляцию и не трогает нормальную жизнь.
///
/// Второй довод сильнее первого: RIPE-580 прямо пишет, что дефолтные
/// настройки RFD «do more harm than good» — при порогах 2000–3000
/// подавлялось 14% префиксов. У них были сотни тысяч префиксов и запас
/// прочности. У НАС ТРИ НОДЫ. Демпфер, доведённый до логического конца,
/// устроил бы отказ в обслуживании сам себе: подавив пару маршрутов, он
/// оставил бы полосу без кандидатов вовсе.
pub const SUPPRESS_ABOVE: f32 = 6000.0;

/// Порог возврата из подавления. Источник: RIPE-580.
///
/// Гистерезис нужен и здесь, не только в выборе маршрута. С одним порогом
/// маршрут, чей штраф колеблется вокруг него, мигал бы между «подавлен» и
/// «разрешён» — тот же дребезг, только этажом выше. Путь с 6000 до 2000 при
/// полураспаде 10 минут занимает 15.8 минуты.
pub const REUSE_BELOW: f32 = 2000.0;

/// Потолок штрафа маршрута.
///
/// Наше решение (в псевдокоде документа потолка нет). Без него штраф растёт
/// неограниченно: маршрут, отфлапавший полсотни раз за время сетевой аварии,
/// набрал бы десятки тысяч и остался подавлен на часы ПОСЛЕ того, как сеть
/// починили. С потолком 12000 максимальное подавление — путь 12000 → 2000,
/// то есть 10·log2(6) ≈ 25.8 минуты. Значение выбрано как удвоенный порог
/// подавления: понятие «максимальный штраф» само взято из RFC 2439.
pub const MAX_PENALTY: f32 = 12_000.0;

/// Потолок осевого штрафа, пункты.
///
/// Наше решение. Осевой штраф вычитается прямо из оценки, а оценка живёт в
/// 0..100 — накопление свыше сотни ничего уже не меняет в порядке маршрутов,
/// зато затухать будет часами, и ось осталась бы мёртвой много позже, чем
/// сеть перестала резать. Ось при этом не исключается совсем: она теряет
/// приоритет, но остаётся последней надеждой, если умрут остальные.
pub const AXIS_PENALTY_CAP: f32 = 100.0;

/// Период полураспада осевого штрафа. Тот же, что у RFD.
///
/// Осевой вердикт пересчитывается каждый цикл, поэтому ожившая ось
/// немедленно перестаёт получать новые штрафы и возвращается сама за
/// десяток-другой минут — отдельного механизма прощения не нужно.
pub const AXIS_PENALTY_HALF_LIFE_MS: u64 = 600_000;

/// Через сколько спокойствия серия переключений считается прерванной.
///
/// Наше решение. «k переключений ПОДРЯД» без срока давности означало бы, что
/// счётчик только растёт: за сутки нормальной работы остывание доползло бы до
/// потолка и полоса перестала бы адаптироваться вообще. Полоса, продержавшая
/// маршрут дольше максимального остывания, не дребезжит по определению —
/// значит, отсчёт можно начинать заново.
pub const STREAK_FORGET_MS: u64 = 1_800_000;

// ─────────────────────────── Вспомогательное ───────────────────────────

/// Величина, экспоненциально затухающая во времени.
///
/// Хранит значение и момент, а не пересчитывает по тику: тиков у ядра нет,
/// время подаётся снаружи и может прийти с любым шагом.
#[derive(Copy, Clone, Debug)]
struct Decaying {
    value: f32,
    at: Instant,
}

impl Decaying {
    fn zero(at: Instant) -> Self {
        Self { value: 0.0, at }
    }

    fn get(&self, now: Instant, half_life_ms: u64) -> f32 {
        if self.value <= 0.0 {
            return 0.0;
        }
        let dt = now.since(self.at) as f32;
        self.value * 0.5f32.powf(dt / half_life_ms as f32)
    }

    /// Затухнуть до `now` и добавить сверху, не выходя за потолок.
    fn add(&mut self, points: f32, now: Instant, half_life_ms: u64, cap: f32) {
        self.value = (self.get(now, half_life_ms) + points).clamp(0.0, cap);
        self.at = now;
    }
}

/// Состояние демпфера по одному маршруту.
#[derive(Clone, Debug)]
struct RouteDamp {
    /// Сглаженная оценка.
    score: Ewma,
    /// Сглаженный КВАДРАТ остатка «сырое минус сглаженное» — из него σ.
    dev2: Ewma,
    dev_samples: u32,
    last_at: Instant,
    penalty: Decaying,
    /// Липкость подавления. `Cell`, потому что решение о выходе из подавления
    /// принимает время, а время приходит только в `is_suppressed(&self)`:
    /// делать метод `&mut` значило бы заставить читателя оценок держать
    /// изменяемую ссылку на весь демпфер. Никакой недетерминированности это
    /// не вносит — состояние по-прежнему функция от поданной истории.
    suppressed: Cell<bool>,
}

impl RouteDamp {
    fn new(at: Instant) -> Self {
        Self {
            score: Ewma::new(SCORE_HALF_LIFE_MS),
            dev2: Ewma::new(NOISE_HALF_LIFE_MS),
            dev_samples: 0,
            last_at: at,
            penalty: Decaying::zero(at),
            suppressed: Cell::new(false),
        }
    }
}

/// Состояние демпфера по одной полосе.
#[derive(Copy, Clone, Debug, Default)]
struct LaneDamp {
    /// Сколько замеров подряд условие входа держится.
    dwell: u8,
    switched_at: Option<Instant>,
    /// Сколько переключений подряд — показатель степени в остывании.
    switch_streak: u32,
}

// ─────────────────────────── Демпфер ───────────────────────────

/// Вся инерция системы: сглаживание, выдержка, остывание, штрафы.
///
/// Карты — `BTreeMap`, а не `HashMap`: порядок обхода обязан быть
/// воспроизводимым, иначе прогон на одном и том же логе даст разные решения
/// при равных оценках, и отладка гистерезиса превратится в гадание.
#[derive(Clone, Debug, Default)]
pub struct DamperState {
    routes: BTreeMap<RouteId, RouteDamp>,
    lanes: BTreeMap<LaneId, LaneDamp>,
    axes: BTreeMap<Axis, Decaying>,
}

impl DamperState {
    pub fn new() -> Self {
        Self::default()
    }

    // ── Сглаживание ──

    /// Учесть сырую оценку и вернуть сглаженную.
    ///
    /// Заодно копит остаток «сырое минус сглаженное» — из него берётся σ для
    /// порога. Считать остаток надо ДО обновления: после обновления
    /// сглаженное уже подтянуто к сырому, и разность занижена.
    pub fn smoothed(&mut self, route: &RouteId, raw: f32, now: Instant) -> f32 {
        let e = self
            .routes
            .entry(route.clone())
            .or_insert_with(|| RouteDamp::new(now));
        let dt = now.since(e.last_at);

        if let Some(prev) = e.score.get() {
            let dev = raw - prev;
            // Винзоризация: в оценку ШУМА одиночный остаток входит обрезанным
            // по трём текущим σ. Иначе настоящий сдвиг качества раздувает σ,
            // порог `2σ` уезжает вслед за ним, и деградация прячется за
            // собственной величиной.
            let dev = if e.dev_samples >= NOISE_MIN_SAMPLES {
                let sigma = e.dev2.get_or(0.0).max(0.0).sqrt();
                dev.clamp(-NOISE_WINSOR_K * sigma, NOISE_WINSOR_K * sigma)
            } else {
                dev
            };
            e.dev2.update(dev * dev, dt);
            e.dev_samples = e.dev_samples.saturating_add(1);
        }
        e.score.update(raw, dt);
        e.last_at = now;
        e.score.get_or(raw)
    }

    /// Сглаженная оценка без обновления. `None` — маршрут ни разу не мерили.
    pub fn smoothed_of(&self, route: &RouteId) -> Option<f32> {
        self.routes.get(route).and_then(|e| e.score.get())
    }

    /// Онлайн-оценка шума оценки, пункты.
    ///
    /// Корень из сглаженного квадрата остатка вокруг сглаженной оценки. Это
    /// смещено вверх примерно на 3% (остаток берётся относительно
    /// экспоненциального среднего, а не истинного центра) — поправку не
    /// вводим сознательно: порог `max(5, 2σ)` от 3% не меняется, а лишняя
    /// формула без измерения, которое её оправдывает, вредит больше.
    pub fn score_noise(&self, route: &RouteId) -> f32 {
        match self.routes.get(route) {
            Some(e) if e.dev_samples >= NOISE_MIN_SAMPLES => e.dev2.get_or(0.0).max(0.0).sqrt(),
            _ => 0.0,
        }
    }

    /// Порог переключения для маршрута: `max(пол, 2σ)`.
    pub fn margin(&self, route: &RouteId, h: &Hysteresis) -> f32 {
        resolve_margin(h.margin_floor, self.score_noise(route))
    }

    // ── Время выдержки ──

    /// Условие держится ещё один замер. Возвращает длину серии.
    ///
    /// Аналог Time-To-Trigger из 3GPP: решение принимается не по одному
    /// удачному сравнению, а по серии. Одиночный выброс в оценке не должен
    /// стоить пользователю разрыва сессий.
    pub fn bump_dwell(&mut self, lane: &LaneId) -> u8 {
        let e = self.lanes.entry(lane.clone()).or_default();
        e.dwell = e.dwell.saturating_add(1);
        e.dwell
    }

    /// Серия прервана: условие перестало выполняться либо переключение уже
    /// состоялось.
    pub fn reset_dwell(&mut self, lane: &LaneId) {
        self.lanes.entry(lane.clone()).or_default().dwell = 0;
    }

    // ── Переключение и остывание ──

    /// Полоса переключена на `route`.
    ///
    /// Штраф за флап вешается на маршрут, в который ВОШЛИ, а не из которого
    /// вышли. Так работает подавление осцилляции: в паре A↔B штрафуются оба,
    /// каждый на своём заходе, и первый добравшийся до порога выбывает —
    /// колебание прекращается. Штраф за выход наказывал бы, наоборот, того,
    /// кто сломался, — а он и так уже исключён воротами.
    pub fn on_switch(&mut self, lane: &LaneId, route: &RouteId, now: Instant) {
        let e = self.lanes.entry(lane.clone()).or_default();
        let streak = match e.switched_at {
            Some(prev) if now.since(prev) >= STREAK_FORGET_MS => 1,
            Some(_) => e.switch_streak.saturating_add(1),
            None => 1,
        };
        e.switch_streak = streak;
        e.switched_at = Some(now);
        e.dwell = 0;

        self.penalize_flap(route, now);
    }

    /// Сколько ещё нельзя переключать эту полосу: `min(база·2^(k−1), потолок)`.
    ///
    /// Источник формы: outlier detection в Envoy — время карантина растёт с
    /// каждым повторным срабатыванием. Смысл прямой: если предыдущее
    /// переключение не помогло, следующее тем более не поможет, а стоит
    /// столько же.
    pub fn cooldown_ms(&self, lane: &LaneId, h: &Hysteresis) -> u64 {
        let k = self.lanes.get(lane).map_or(0, |e| e.switch_streak);
        if k == 0 {
            return 0;
        }
        // Сдвиг ограничен: 2^63 уже больше любого потолка, дальше только UB.
        let shift = (k - 1).min(62);
        h.cooldown_ms
            .saturating_mul(1u64 << shift)
            .min(h.cooldown_max_ms)
    }

    /// Когда полосу переключили в последний раз.
    pub fn switched_at(&self, lane: &LaneId) -> Option<Instant> {
        self.lanes.get(lane).and_then(|e| e.switched_at)
    }

    /// Длина текущей серии переключений — то самое `k` в остывании.
    pub fn switch_streak(&self, lane: &LaneId) -> u32 {
        self.lanes.get(lane).map_or(0, |e| e.switch_streak)
    }

    // ── Штраф за дребезг ──

    /// Начислить штраф за флап. Публично, потому что флапом считается не
    /// только наше переключение: маршрут, поднявшийся и упавший сам, дребезжит
    /// ровно так же.
    pub fn penalize_flap(&mut self, route: &RouteId, now: Instant) {
        self.routes
            .entry(route.clone())
            .or_insert_with(|| RouteDamp::new(now))
            .penalty
            .add(FLAP_PENALTY, now, PENALTY_HALF_LIFE_MS, MAX_PENALTY);
    }

    /// Текущий штраф маршрута с учётом затухания.
    pub fn penalty(&self, route: &RouteId, now: Instant) -> f32 {
        self.routes
            .get(route)
            .map_or(0.0, |e| e.penalty.get(now, PENALTY_HALF_LIFE_MS))
    }

    /// Подавлен ли маршрут.
    ///
    /// Два порога, а не один: выше 6000 подавляем, ниже 2000 возвращаем, между
    /// ними держим прежнее решение. Ровно та же асимметрия входа и выхода, что
    /// и в выборе маршрута, и по той же причине.
    ///
    /// ВАЖНО: этот метод — не последнее слово. Инвариант контура решений
    /// (раздел 6.3, шаг 4) гласит, что демпфер никогда не исключает последний
    /// живой маршрут; если подавление вычистило всех кандидатов, оно
    /// игнорируется целиком. Здесь этого нет намеренно — демпфер не знает,
    /// сколько всего кандидатов у полосы, и знать не должен.
    pub fn is_suppressed(&self, route: &RouteId, now: Instant) -> bool {
        let Some(e) = self.routes.get(route) else {
            return false;
        };
        let p = e.penalty.get(now, PENALTY_HALF_LIFE_MS);
        if p > SUPPRESS_ABOVE {
            e.suppressed.set(true);
        } else if p < REUSE_BELOW {
            e.suppressed.set(false);
        }
        e.suppressed.get()
    }

    // ── Осевой штраф ──

    /// Наказать ОСЬ, а не узлы.
    ///
    /// Когда все маршруты одной оси мертвы на разных узлах, виновата сеть, а
    /// не серверы: так выглядит фильтрация QUIC, при которой Hysteria2 и TUIC
    /// ложатся разом, а TCP-оси дают свои сорок мегабит. Штрафовать узлы в
    /// этом случае — наказывать исправное железо и потом ещё ждать, пока оно
    /// «выздоровеет».
    pub fn penalize_axis(&mut self, axis: Axis, points: f32, now: Instant) {
        self.axes
            .entry(axis)
            .or_insert_with(|| Decaying::zero(now))
            .add(
                points,
                now,
                AXIS_PENALTY_HALF_LIFE_MS,
                AXIS_PENALTY_CAP,
            );
    }

    /// Осевой штраф в пунктах оценки. Вычитается из оценки КАЖДОГО маршрута
    /// этой оси, на каком бы узле он ни жил.
    pub fn axis_penalty_points(&self, axis: Axis, now: Instant) -> f32 {
        self.axes
            .get(&axis)
            .map_or(0.0, |d| d.get(now, AXIS_PENALTY_HALF_LIFE_MS))
    }

    /// Забыть всё про маршрут. Нужно при смене сети: накопленное через другой
    /// канал ни с чем не сравнимо, а штраф за флапы в чужой сети — тем более
    /// не свойство маршрута.
    pub fn forget_route(&mut self, route: &RouteId) {
        self.routes.remove(route);
    }
}

// ─────────────────────────── Свободные функции ───────────────────────────

/// Порог переключения: `max(пол, 2σ)`.
///
/// Порог ниже шума оценки бессмыслен при любом сглаживании — измерение
/// (раздел 6.1) прямо это показывает: margin 2 при α=1/8 дал 8 ложных
/// переключений за час, margin 5 при той же α — ноль.
pub fn resolve_margin(floor: f32, sigma: f32) -> f32 {
    floor.max(MARGIN_SIGMA_K * sigma)
}

/// Бонус действующему маршруту: 3 пункта сразу после переключения, линейно до
/// нуля за 10 минут.
///
/// Спад линейный, а не экспоненциальный, сознательно: экспонента никогда не
/// достигает нуля, и через час у инкумбента оставалась бы призрачная фора,
/// которую никто уже не помнит. Здесь важно, чтобы бонус кончился насовсем.
pub fn incumbent_bonus(switched_at: Instant, now: Instant) -> f32 {
    let dt = now.since(switched_at);
    if dt >= INCUMBENT_DECAY_MS {
        return 0.0;
    }
    INCUMBENT_BONUS_POINTS * (1.0 - dt as f32 / INCUMBENT_DECAY_MS as f32)
}

/// Условие ВХОДА: событие A3 из 3GPP TS 36.331.
///
/// ```text
/// вход:  S_cand − Hys ≥ S_curr + margin + sticky
/// ```
///
/// Кандидат обязан быть лучше не просто так, а на порог, на бонус инкумбенту
/// и ещё на половину полосы гистерезиса сверху.
pub fn should_enter(cand: f32, curr: f32, margin: f32, sticky: f32, hys: f32) -> bool {
    cand - hys >= curr + margin + sticky
}

/// Условие ВЫХОДА: то же событие A3, зеркально.
///
/// ```text
/// выход: S_cand + Hys < S_curr + margin + sticky
/// ```
///
/// Именно асимметрия входа и выхода отличает настоящий гистерезис от простого
/// порога, и именно её обычно забывают. Между двумя условиями лежит мёртвая
/// зона шириной `2·Hys`: попав в неё, система НЕ меняет решения — ни начатый
/// отсчёт выдержки не сбрасывает, ни переключения не делает. Без мёртвой зоны
/// кандидат, колеблющийся ровно вокруг порога, сбрасывал бы счётчик выдержки
/// на каждом втором замере, и переключение не состоялось бы никогда — даже
/// когда оно объективно нужно.
pub fn should_exit(cand: f32, curr: f32, margin: f32, sticky: f32, hys: f32) -> bool {
    cand + hys < curr + margin + sticky
}

