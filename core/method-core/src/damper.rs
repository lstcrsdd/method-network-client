//! Демпфер: сглаживание оценки, порог входа, время выдержки, остывание и
//! штраф за дребезг.
//!
//! Здесь живёт вся инерция системы и больше нигде. Причина такого сбора в
//! одном месте — измерение: два ОБЪЕКТИВНО одинаковых маршрута при шаге 5 с
//! дают ложные переключения без сглаживания и ноль с ним (раздел 6.1
//! проектного документа: 9 за час; наш тест `одинаковые_маршруты_не_дают_
//! ложных_переключений` — 22 за пять часов против нуля). Каждое ложное
//! переключение — это разрыв живых сессий ради нуля выигрыша.
//!
//! Четыре механизма нужны ВМЕСТЕ: убрать любой — дребезг возвращается.
//! Сглаживание снижает ложные переключения сильнее, чем удвоение порога, но
//! в одиночку не спасает: без выдержки и остывания одна удачная серия проб
//! всё равно уводит полосу.
//!
//! Времени здесь нет своего: `now` подаётся снаружи, часов модуль не читает.
//! Это условие проверяемости — весь час симуляции ниже прогоняется за
//! миллисекунды на записанном ряде чисел, без сети и без сна.
//!
//! Состояние демпфера НЕ сериализуется намеренно: оно целиком выражено в
//! монотонных часах, а они обнуляются при перезапуске. Восстановленный из
//! файла `switched_at` означал бы остывание из чужой эпохи — либо вечный
//! запрет, либо мгновенное разрешение.

