#!/usr/bin/env bash
#
# Создание релизного ключа подписи.
#
# Ключ кладётся ВНЕ репозитория — по умолчанию в ~/.method-keys. Ключ, лежащий
# в проекте, перестаёт быть ключом: любой, у кого есть копия репозитория,
# сможет подписать поддельное обновление, и Android установит его поверх
# настоящего как родное.
#
# Пароль скрипт не принимает, не хранит и не печатает — его спрашивает сам
# keytool, напрямую у человека. Пароль, прошедший через аргументы командной
# строки, виден в списке процессов и остаётся в истории оболочки.
#
# ГЛАВНОЕ, ЧТО НАДО ПОНИМАТЬ ПРО ЭТОТ КЛЮЧ.
# Сменить его после публикации нельзя. Android опознаёт обновление по подписи:
# сборка, подписанная другим ключом, — для системы ДРУГОЕ приложение, и она
# откажется ставить её поверх. Люди будут вынуждены удалить клиент вместе с
# подписками, сценариями и правилами по приложениям.
# Потеря ключа = потеря возможности выпускать обновления. Насовсем.
set -euo pipefail

JBR="/Applications/Android Studio.app/Contents/jbr/Contents/Home"
KEYTOOL="$JBR/bin/keytool"
[ -x "$KEYTOOL" ] || KEYTOOL="$(command -v keytool || true)"
[ -x "$KEYTOOL" ] || { echo "keytool не найден: поставьте JDK или Android Studio" >&2; exit 1; }

KEYS_DIR="${METHOD_KEYS_DIR:-$HOME/.method-keys}"
KEYSTORE="${METHOD_KEYSTORE:-$KEYS_DIR/method-release.jks}"
ALIAS="${METHOD_KEY_ALIAS:-method}"

if [ -f "$KEYSTORE" ]; then
    echo "Ключ уже есть: $KEYSTORE"
    echo "Перезаписывать его НЕЛЬЗЯ — старый ключ потеряется, а вместе с ним"
    echo "возможность обновлять уже установленные копии клиента."
    exit 1
fi

mkdir -p "$KEYS_DIR"
chmod 700 "$KEYS_DIR"

cat <<'TEXT'
Сейчас keytool спросит пароль хранилища, а затем данные владельца.

  · Пароль придумайте сами и сохраните в менеджере паролей ПРЯМО СЕЙЧАС.
    Восстановить его нельзя: без пароля ключ бесполезен ровно так же, как
    если бы он был потерян.
  · «Имя и фамилия» (CN) — это не паспортные данные, а имя, под которым
    приложение подписано. Осмысленно: Method Network.
  · Срок — 10000 дней (27 лет). Ключ, истёкший раньше, чем закончится жизнь
    приложения, означает то же самое, что потерянный.

TEXT

"$KEYTOOL" -genkeypair -v \
    -keystore "$KEYSTORE" \
    -alias "$ALIAS" \
    -keyalg RSA -keysize 4096 \
    -validity 10000

chmod 600 "$KEYSTORE"

echo
echo "Ключ создан: $KEYSTORE"
echo "Права: только владелец (600), каталог 700."
echo
# Отпечаток. Пароль спрашивает keytool сам, поэтому его вывод НЕ глушим:
# заглушенный stderr съедал приглашение, и человек видел молчаливое зависание.
# И не роняем скрипт на пустом grep — из-за `set -e` это обрывало инструкцию
# на самом полезном месте.
echo "Отпечаток — сверяйте его после каждой сборки релиза."
echo "Введите пароль ещё раз, чтобы keytool показал сертификат:"
"$KEYTOOL" -list -v -keystore "$KEYSTORE" -alias "$ALIAS" \
    | grep -E "SHA256:|Valid from" | sed 's/^[[:space:]]*/  /' || true

cat <<TEXT

Что сделать прямо сейчас, пока не забылось:

  1. Записать пароль в менеджер паролей.
  2. Сделать копию файла $KEYSTORE в другое место —
     не на этом же диске. Сгорит диск — сгорит возможность обновлять клиент.
  3. Проверить, что ключ не попадёт в git:
       git check-ignore -v "$KEYSTORE" || echo "ключ вне репозитория — хорошо"

Сборка релиза после этого:

  METHOD_RELEASE=1 ./build-apk.sh

Пароль спросят при сборке. В переменные окружения его класть не нужно и не
стоит: переменные наследуются дочерними процессами и попадают в дампы.
TEXT
